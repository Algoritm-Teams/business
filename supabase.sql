create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 50),
  rating integer not null check (rating between 1 and 5),
  message text not null check (char_length(btrim(message)) between 1 and 1500),
  status text not null default 'pending' check (status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

alter table public.reviews enable row level security;

grant select, insert on public.reviews to anon, authenticated;

drop policy if exists "Anyone can read approved reviews" on public.reviews;
create policy "Anyone can read approved reviews"
on public.reviews for select
to anon, authenticated
using (status = 'approved');

drop policy if exists "Visitors can submit pending reviews" on public.reviews;
create policy "Visitors can submit pending reviews"
on public.reviews for insert
to anon, authenticated
with check (status = 'pending');

-- Публичные посетители не получают права менять или удалять отзывы.
